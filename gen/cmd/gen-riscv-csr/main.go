// Command gen-riscv-csr builds the RISC-V CSR name table consumed by the
// "rv_csr" field transform (see arch/riscv/transforms.go).
//
// It parses the canonical encoding header from the riscv-isa-sim (Spike)
// project — arch/riscv/data/encoding.h — which lists every standard CSR as
// `#define CSR_<NAME> 0x<ADDR>`. The address (12-bit) is the map key; the name
// is the lowercased mnemonic (CSR_FFLAGS -> fflags) as objdump prints it.
//
// Output: arch/riscv/csr_generated.go, `var rvCsrNames = map[uint32]string{...}`.
//
// Usage:
//
//	go run ./gen/cmd/gen-riscv-csr -i arch/riscv/data/encoding.h -o arch/riscv/csr_generated.go
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"slices"
	"strings"

	"github.com/okneniz/assembly/gen/riscv/enchdr"
)

func main() {
	in := flag.String("i", "arch/riscv/data/encoding.h", "Spike encoding.h path")
	out := flag.String("o", "arch/riscv/csr_generated.go", "output Go file")
	flag.Parse()

	requireData(*in)

	data, err := os.ReadFile(*in)
	if err != nil {
		log.Fatalf("read %s: %v", *in, err)
	}

	header, perr := enchdr.Parse([]rune(string(data)))
	if perr != nil {
		log.Fatalf("parse %s: %v (at %s)", *in, perr, perr.Position())
	}

	// First-wins per address for determinism. (Some addresses have more than one
	// name across extensions; the canonical common CSRs all appear here.)
	names := map[uint32]string{}
	var dup int
	for _, c := range header.CSRs {
		if _, exists := names[c.Value]; exists {
			dup++
			continue
		}

		names[c.Value] = strings.ToLower(c.Name)
	}

	log.Printf("parsed %d CSRs (%d duplicate addresses skipped)", len(names), dup)
	emit(*out, names)
}

// requireData fails fast with an actionable hint if the vendored encoding.h is
// absent (it is gitignored and must be fetched first).
func requireData(path string) {
	if _, err := os.Stat(path); err != nil {
		fmt.Fprintf(os.Stderr, "\nerror: %s not found\n", path)
		fmt.Fprintf(
			os.Stderr,
			"       It is gitignored (canonical, regenerable) and must be downloaded.\n\n",
		)
		fmt.Fprintf(os.Stderr, "       Fix:    make update-riscv-csr-data\n")
		fmt.Fprintf(os.Stderr, "       Then:  make gen-riscv-csr\n\n")
		os.Exit(1)
	}
}

func emit(outPath string, names map[uint32]string) {
	keys := make([]uint32, 0, len(names))
	for k := range names {
		keys = append(keys, k)
	}

	slices.Sort(keys)

	var b strings.Builder
	fmt.Fprintln(&b, "// Code generated by gen/cmd/gen-riscv-csr; DO NOT EDIT.")
	fmt.Fprintln(&b, "//")
	fmt.Fprintln(&b, "// RISC-V CSR names, parsed from the canonical Spike encoding header")
	fmt.Fprintln(&b, "// (arch/riscv/data/encoding.h). Keyed by the 12-bit CSR address")
	fmt.Fprintln(&b, "// (bits[31:20] of csrr*); value is the mnemonic objdump prints.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package riscv")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "var rvCsrNames = map[uint32]string{")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t0x%03x: %q,\n", k, names[k])
	}

	fmt.Fprintln(&b, "}")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		log.Fatalf("write %s: %v", outPath, err)
	}

	log.Printf("wrote %d CSR names to %s", len(names), outPath)
}
