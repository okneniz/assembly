// Command gen-riscv-instr builds the RISC-V instruction encoding table from the
// canonical Spike encoding header (arch/riscv/data/encoding.h), the same source
// gen-riscv-csr uses for CSR names.
//
// encoding.h lists every standard instruction as a MATCH/MASK pair plus a
// DECLARE_INSN(name, MATCH_X, MASK_X) line. This command parses those into
// name → {match, mask}, the authoritative decode data (the hand-written
// decodeTable in arch/riscv/decode.go supplies only the formatting/operand
// config and joins by mnemonic). This is the RISC-V side of "decode data-driven
// from the canonical source"; ARM uses its official XML instead.
//
// Output: arch/riscv/instr_generated.go, `var riscvEncodings = map[string][2]uint32{...}`
// keyed by the lowercased encoding.h name (e.g. "addi", "fadd_s"), value is
// {match, mask}.
//
// Usage:
//
//	go run ./gen/cmd/gen-riscv-instr -i arch/riscv/data/encoding.h -o arch/riscv/instr_generated.go
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"

	"github.com/okneniz/assembly/gen/riscv/enchdr"
)

type enc struct {
	match, mask uint32
}

func newEnc(match uint32, mask uint32) enc {
	return enc{
		match: match,
		mask:  mask,
	}
}

func main() {
	in := flag.String("i", "arch/riscv/data/encoding.h", "Spike encoding.h path")
	out := flag.String("o", "arch/riscv/instr_generated.go", "output Go file")
	flag.Parse()

	requireData(*in)

	data, err := os.ReadFile(*in)
	if err != nil {
		log.Fatalf("read %s: %v", *in, err)
	}

	header, perr := enchdr.Parse([]rune(string(data)))
	if perr != nil {
		log.Fatalf("parse %s: %v (at %s)", *in, perr, perr.Position())
	}

	// Pass 1: collect MATCH_/MASK_ macro values.
	macros := map[string]uint32{}
	for _, m := range header.Macros {
		macros[m.Name] = m.Value
	}

	// Pass 2: DECLARE_INSN associates a lowercase name with its macro pair.
	encs := map[string]enc{}
	for _, d := range header.Insns {
		match, ok1 := macros[d.MatchName]
		mask, ok2 := macros[d.MaskName]
		if !ok1 || !ok2 {
			continue
		}

		if _, exists := encs[d.Name]; !exists {
			encs[d.Name] = newEnc(match, mask)
		}
	}

	log.Printf("parsed %d instruction encodings", len(encs))
	emit(*out, encs)
}

// requireData fails fast with an actionable hint if the vendored encoding.h is
// absent (it is gitignored and must be fetched first).
func requireData(path string) {
	if _, err := os.Stat(path); err != nil {
		fmt.Fprintf(os.Stderr, "\nerror: %s not found\n", path)
		fmt.Fprintf(
			os.Stderr,
			"       It is gitignored (canonical, regenerable) and must be downloaded.\n\n",
		)
		fmt.Fprintf(os.Stderr, "       Fix:    make update-riscv-csr-data\n")
		fmt.Fprintf(os.Stderr, "       Then:  make gen-riscv-instr\n\n")
		os.Exit(1)
	}
}

func emit(outPath string, encs map[string]enc) {
	names := make([]string, 0, len(encs))
	for n := range encs {
		names = append(names, n)
	}

	sort.Strings(names)

	var b strings.Builder
	fmt.Fprintln(&b, "// Code generated by gen/cmd/gen-riscv-instr; DO NOT EDIT.")
	fmt.Fprintln(&b, "//")
	fmt.Fprintln(&b, "// RISC-V instruction encodings, parsed from the canonical Spike encoding")
	fmt.Fprintln(&b, "// header (arch/riscv/data/encoding.h). Keyed by the lowercased encoding.h")
	fmt.Fprintln(&b, "// name; value is {match, mask} — the authoritative decode data. The")
	fmt.Fprintln(&b, "// the hand-written decodeTable (decode.go) joins by mnemonic to supply")
	fmt.Fprintln(&b, "// operand/format config; only that subset is matched at decode time.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package riscv")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "// riscvEncodings[name] = {match, mask}.")
	fmt.Fprintln(&b, "var riscvEncodings = map[string][2]uint32{")
	for _, n := range names {
		e := encs[n]
		fmt.Fprintf(&b, "\t%q: {0x%x, 0x%x},\n", n, e.match, e.mask)
	}

	fmt.Fprintln(&b, "}")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		log.Fatalf("write %s: %v", outPath, err)
	}

	log.Printf("wrote %d instruction encodings to %s", len(encs), outPath)
}
